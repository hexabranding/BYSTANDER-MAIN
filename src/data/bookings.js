const money = (rate, hours) => {
  const subtotal = rate * hours
  const platformFee = PLATFORM_FEE
  const commission = Math.round(subtotal * PLATFORM_COMMISSION)
  const tax = Math.round((subtotal + platformFee) * GST_RATE)
  return {
    hourlyRate: rate,
    hours,
    subtotal,
    platformFee,
    commission,
    tax,
    total: subtotal + platformFee + tax,
  }
}

const build = (o) => {
  const price = money(o.rate, o.hours)
  return {
    id: o.id,
    ref: o.ref,
    customerId: o.customerId,
    caregiverId: o.caregiverId,
    service: o.service,
    patient: o.patient,
    careType: o.careType,
    address: o.address,
    city: o.city,
    date: o.date,
    startTime: o.startTime,
    hours: o.hours,
    status: o.status,
    paymentStatus: o.paymentStatus,
    createdAt: o.createdAt,
    notes: o.notes || '',
    specialInstructions: o.specialInstructions || '',
    invoiceNo: o.invoiceNo,
    ...price,
    timeline: o.timeline || [
      { label: 'Booking requested', status: 'completed', at: o.createdAt },
      {
        label: 'Caregiver assigned',
        status: ['Pending'].includes(o.status) ? 'upcoming' : 'completed',
        at: o.status === 'Pending' ? null : o.date,
      },
      {
        label: 'Service started',
        status: ['In Progress', 'Completed'].includes(o.status) ? 'completed' : 'upcoming',
        at: ['In Progress', 'Completed'].includes(o.status) ? o.date : null,
      },
      {
        label: 'Service completed',
        status: o.status === 'Completed' ? 'completed' : 'upcoming',
        at: o.status === 'Completed' ? o.date : null,
      },
      {
        label: 'Payment settled',
        status: o.paymentStatus === 'Paid' ? 'completed' : 'upcoming',
        at: o.paymentStatus === 'Paid' ? o.date : null,
      },
    ],
  }
}

